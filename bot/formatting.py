"""Экранирование текста для сообщений бота.

Бот отправляет сообщения с HTML-разметкой (жирный текст и т.п.), поэтому
любой текст, который ввёл пользователь сам (имя, город...) и который потом
показывается ДРУГОМУ человеку, нужно экранировать — иначе кто-то может
вписать в своё имя HTML-код и сломать сообщение или вставить в него ссылку.
"""

import html


def escape(text: str) -> str:
    return html.escape(text)
